import { build } from 'esbuild'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)))
const lib = path.join(root, 'lib')
const tmp = path.join(root, '.build')

await rm(lib, { recursive: true, force: true })
await rm(tmp, { recursive: true, force: true })
await mkdir(lib, { recursive: true })
await mkdir(tmp, { recursive: true })

await build({
  entryPoints: [path.join(root, 'src/host/index.ts')],
  outfile: path.join(lib, 'index.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  external: ['ali-oss'],
  sourcemap: true,
  legalComments: 'none',
  logLevel: 'info',
})

const clientIntermediate = path.join(tmp, 'client.cjs')
await build({
  entryPoints: [path.join(root, 'src/client/index.tsx')],
  outfile: clientIntermediate,
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2020',
  external: ['react'],
  jsx: 'transform',
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'info',
})

const clientCode = await readFile(clientIntermediate, 'utf8')
const indented = clientCode.split('\n').map((line) => (line === '' ? '' : `    ${line}`)).join('\n')
const wrapped = [
  '/* dsh-asset-archiver client bundle — generated by scripts/build.mjs */',
  'window.__ModuleLoader__.load({',
  "  id: 'dsh-asset-archiver',",
  '  factory(require) {',
  '    const module = { exports: {} };',
  '    const exports = module.exports;',
  indented,
  '    return module.exports;',
  '  },',
  '});',
  '',
].join('\n')

await writeFile(path.join(lib, 'client.js'), wrapped, 'utf8')

await rm(tmp, { recursive: true, force: true })
console.log('built lib/index.js and lib/client.js')
